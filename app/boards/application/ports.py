"""What the use cases need from the outside world. infrastructure/ provides it; tests fake it."""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Iterable, Optional, Protocol

from boards.domain.model import Board, BoardList, Card, Workspace


class Duplicate(Exception):
    """A plain INSERT met an existing key (SQLSTATE 23505): someone else claimed it first."""


@dataclass
class Event:
    """One line of the activity log: who did what, when, and the exact field changes."""
    id: str
    workspace_id: str
    board_id: Optional[str]
    card_number: Optional[int]
    actor: str
    action: str
    changes: list = field(default_factory=list)  # [{field, before, after}]
    at: Optional[datetime] = None


class Repository(Protocol):
    # workspaces and their people
    def get_workspace(self, workspace_id: str) -> Optional[Workspace]: ...
    def workspaces_for(self, email: str) -> list: ...
    def save_workspace(self, ws: Workspace) -> None: ...
    def remove_workspace_member(self, workspace_id: str, email: str) -> None: ...

    # boards, their people and lists
    def get_board(self, board_id: str) -> Optional[Board]: ...
    def boards_in(self, workspace_ids: Iterable[str]) -> list: ...
    def save_board(self, board: Board) -> None: ...
    def remove_board_member(self, board_id: str, email: str) -> None: ...
    def lists_on(self, board_ids: Iterable[str]) -> list: ...
    def save_list(self, lst: BoardList) -> None: ...

    # cards
    def get_card(self, number: int) -> Optional[Card]: ...
    def cards_on(self, board_ids: Iterable[str]) -> list: ...
    def max_card_number(self) -> int: ...
    def insert_card(self, card: Card) -> None: ...            # plain INSERT; raises Duplicate
    def update_card(self, card: Card, expected_version: int) -> bool: ...  # False if stale

    # "blocked by" links
    def links_on(self, board_ids: Iterable[str]) -> list: ...  # [(card, blocked_by)]
    def add_link(self, board_id: str, card: int, blocked_by: int, by: str) -> None: ...
    def remove_link(self, card: int, blocked_by: int) -> None: ...

    # history
    def log(self, event: Event) -> None: ...
    def card_history(self, number: int, limit: int = 100) -> list: ...
    def board_activity(self, board_id: str, since: Optional[datetime], limit: int) -> list: ...


class Assistant(Protocol):
    """Dodil Models behind a port, so tests run without a network."""
    def checklist(self, title: str, description: str) -> list: ...
    def summarize(self, facts: str) -> str: ...
    def embed(self, text: str) -> list: ...


class VectorIndex(Protocol):
    """Embeddings of cards, for "find cards like this one"."""
    def upsert(self, number: int, board_id: str, vector: list) -> None: ...
    def has(self, number: int) -> bool: ...
    def nearest(self, vector: list, board_ids: list, k: int) -> list: ...  # [(number, distance)]
